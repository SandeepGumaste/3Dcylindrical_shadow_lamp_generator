#!/usr/bin/env node
// Copies backend/src/contracts/*.ts to frontend/src/contracts/ (generated, never edited by hand).
// `--check` changes nothing and exits 1 naming each file that is missing or differs.
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const check = process.argv.includes('--check');
const src = join(process.cwd(), 'backend/src/contracts');
const dst = join(process.cwd(), 'frontend/src/contracts');
const HEADER = '// Generated by scripts/sync-contracts.mjs from backend/src/contracts. Do not edit.\n\n';

const files = readdirSync(src).filter((f) => f.endsWith('.ts'));
const stale = [];
for (const f of files) {
  const want = HEADER + readFileSync(join(src, f), 'utf8');
  const target = join(dst, f);
  const have = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (have === want) continue;
  if (check) stale.push(f);
  else {
    mkdirSync(dst, { recursive: true });
    writeFileSync(target, want);
  }
}
if (stale.length) {
  console.error(`frontend/src/contracts is out of date: ${stale.join(', ')}. Run: node scripts/sync-contracts.mjs`);
  process.exit(1);
}
